import hashlib
import subprocess
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterator
from uuid import uuid4

from ml_infra.config import RunConfig, config_hash
from ml_infra.results_db import ResultsDatabase


def utc_now() -> str:
    """Return the current UTC timestamp in ISO-8601 format."""

    return datetime.now(timezone.utc).isoformat()


def get_git_commit(
    repo_root: str | Path | None = None,
) -> str | None:
    """
    Return the current Git commit hash.

    Returns None when Git information is unavailable.
    """

    try:
        result = subprocess.run(
            [
                "git",
                "rev-parse",
                "HEAD",
            ],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=True,
        )

        commit = result.stdout.strip()

        return commit or None

    except (
        subprocess.SubprocessError,
        FileNotFoundError,
    ):
        return None


def sha256_file(path: Path) -> str:
    """Calculate SHA-256 checksum of a file."""

    digest = hashlib.sha256()

    with path.open("rb") as file:
        while chunk := file.read(1024 * 1024):
            digest.update(chunk)

    return digest.hexdigest()


class ActiveRun:
    """
    Handle for an experiment that is currently running.
    """

    def __init__(
        self,
        tracker: "ExperimentTracker",
        run_id: str,
    ):
        self._tracker = tracker
        self.run_id = run_id

    def log_metric(
        self,
        name: str,
        value: float,
        *,
        step: int | None = None,
    ) -> None:
        """Log a numerical metric."""

        self._tracker.db.log_metric(
            run_id=self.run_id,
            name=name,
            value=float(value),
            step=step,
            timestamp=utc_now(),
        )

    def log_param(
        self,
        name: str,
        value: Any,
    ) -> None:
        """Log a parameter."""

        self._tracker.db.log_param(
            run_id=self.run_id,
            name=name,
            value=value,
        )

    def log_artifact(
        self,
        path: str | Path,
        *,
        name: str | None = None,
        artifact_type: str | None = None,
    ) -> None:
        """
        Register a file generated by the experiment.
        """

        path = Path(path)

        if not path.exists():
            raise FileNotFoundError(
                f"Artifact does not exist: {path}"
            )

        if not path.is_file():
            raise ValueError(
                f"Artifact must be a file: {path}"
            )

        artifact_name = name or path.name

        self._tracker.db.register_artifact(
            run_id=self.run_id,
            name=artifact_name,
            path=str(path.resolve()),
            artifact_type=artifact_type,
            size_bytes=path.stat().st_size,
            sha256=sha256_file(path),
            created_at=utc_now(),
        )


class ExperimentTracker:
    """
    Public API for tracking reproducible ML experiments.
    """

    def __init__(
        self,
        db: ResultsDatabase,
    ):
        self.db = db

    @contextmanager
    def run(
        self,
        config: RunConfig,
        *,
        dataset_version: str | None = None,
        git_commit: str | None = None,
        repo_root: str | Path | None = None,
    ) -> Iterator[ActiveRun]:
        """
        Start an experiment run.

        Successful execution marks the run as completed.
        Exceptions mark the run as failed and are re-raised.
        """

        run_id = uuid4().hex

        resolved_git_commit = (
            git_commit
            if git_commit is not None
            else get_git_commit(repo_root)
        )

        self.db.create_run(
            run_id=run_id,
            project=config.project,
            run_name=config.run_name,
            seed=config.seed,
            config_hash=config_hash(config),
            config=config.model_dump(mode="json"),
            git_commit=resolved_git_commit,
            dataset_version=dataset_version,
            started_at=utc_now(),
            tags=config.tags,
        )

        active_run = ActiveRun(
            tracker=self,
            run_id=run_id,
        )

        try:
            yield active_run

        except Exception:
            self.db.fail_run(
                run_id,
                ended_at=utc_now(),
            )
            raise

        else:
            self.db.complete_run(
                run_id,
                ended_at=utc_now(),
            )